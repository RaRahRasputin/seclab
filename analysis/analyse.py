#!/usr/bin/env python3
"""SecLab results analysis.

Reads the raw CSV files written by tests/run-tests.sh and tests/bench.sh and produces
    results/summary.md          tables ready to paste into the report
    results/fig-latency.png     latency distributions per condition
    results/fig-capacity.png    requests per second, with and without keep-alive
    results/fig-throughput.png  bulk transfer throughput
    results/fig-attacks.png     attack outcome matrix, baseline vs hardened

Run on the lab host from the repository root:
    sudo apt install -y python3-pandas python3-matplotlib python3-scipy
    python3 analysis/analyse.py

Statistical choices (be ready to explain them):
  * Latency distributions are skewed, with a long tail, so they are summarised
    by the MEDIAN and the 95th/99th percentiles, not only the mean.
  * The difference between two conditions is reported as the difference of
    medians with a 95 % bootstrap confidence interval (10 000 resamples).
  * The Mann-Whitney U test is used to compare two conditions because it makes
    no assumption that the data are normally distributed.
"""
from pathlib import Path

import matplotlib
matplotlib.use("Agg")                       # draw to files, no display needed
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

try:
    from scipy.stats import mannwhitneyu
except ImportError:                         # scipy is optional
    mannwhitneyu = None

BENCH = Path("evidence/bench")
EVIDENCE = Path("evidence")
OUT = Path("results")
OUT.mkdir(exist_ok=True)
RNG = np.random.default_rng(42)             # fixed seed: results are reproducible
ORDER = ["baseline", "hardened-noids", "hardened"]


def load(pattern: str) -> pd.DataFrame:
    files = sorted(BENCH.glob(pattern))
    if not files:
        return pd.DataFrame()
    return pd.concat([pd.read_csv(f) for f in files], ignore_index=True)


def labels_present(df: pd.DataFrame) -> list:
    found = list(df["label"].unique())
    return [l for l in ORDER if l in found] + [l for l in found if l not in ORDER]


def bootstrap_median_diff(a: np.ndarray, b: np.ndarray, n: int = 10_000):
    """95 % confidence interval for median(b) - median(a)."""
    diffs = np.empty(n)
    for i in range(n):
        diffs[i] = np.median(RNG.choice(b, b.size)) - np.median(RNG.choice(a, a.size))
    return np.percentile(diffs, [2.5, 97.5])


lines = ["# SecLab results summary", "",
         "Generated by `analysis/analyse.py` from the raw files in `evidence/`.", ""]

# ----------------------------------------------------------------- latency --
lat = pd.concat([load("latency-cold-*.csv"), load("latency-warm-*.csv")], ignore_index=True)
if not lat.empty:
    lat = lat[lat["http_code"] == 200]
    # Sample 0 of each warm series is the request that OPENED the connection.
    lat = lat[~((lat["series"] == "warm") & (lat["sample"] == 0))]
    lat["ms"] = lat["t_total"] * 1000
    labels = labels_present(lat)

    lines += ["## 1. Request latency (GET /api/summary, milliseconds)", "",
              "| Series | Condition | n | median | mean | p95 | p99 | std dev |",
              "|---|---|---|---|---|---|---|---|"]
    for series in ["cold", "warm"]:
        for label in labels:
            x = lat[(lat["series"] == series) & (lat["label"] == label)]["ms"]
            if x.empty:
                continue
            lines.append(f"| {series} | {label} | {x.size} | {x.median():.2f} | {x.mean():.2f} | "
                         f"{x.quantile(0.95):.2f} | {x.quantile(0.99):.2f} | {x.std():.2f} |")
    lines.append("")

    if "baseline" in labels:
        lines += ["### Difference from baseline (median, ms)", "",
                  "| Series | Condition | median difference | 95 % CI (bootstrap) "
                  "| Mann-Whitney p |",
                  "|---|---|---|---|---|"]
        for series in ["cold", "warm"]:
            base = lat[(lat["series"] == series) & (lat["label"] == "baseline")]["ms"].to_numpy()
            for label in [l for l in labels if l != "baseline"]:
                x = lat[(lat["series"] == series) & (lat["label"] == label)]["ms"].to_numpy()
                if base.size == 0 or x.size == 0:
                    continue
                lo, hi = bootstrap_median_diff(base, x)
                if mannwhitneyu:
                    p = f"{mannwhitneyu(base, x).pvalue:.2e}"
                else:
                    p = "n/a (scipy not installed)"
                lines.append(f"| {series} | {label} | {np.median(x) - np.median(base):+.2f} | "
                             f"[{lo:+.2f}, {hi:+.2f}] | {p} |")
        lines.append("")

    fig, axes = plt.subplots(1, 2, figsize=(10, 4))
    for ax, series, title in zip(axes, ["cold", "warm"],
                                 ["New connection per request", "Connection reused"]):
        data = [lat[(lat["series"] == series) & (lat["label"] == l)]["ms"] for l in labels]
        ax.boxplot(data, showfliers=False)
        ax.set_xticks(range(1, len(labels) + 1), labels)
        ax.set_title(title)
        ax.set_ylabel("request latency (ms)")
        ax.set_ylim(bottom=0)
        ax.grid(axis="y", alpha=0.3)
    fig.suptitle("Latency of GET /api/summary (box = quartiles, line = median, whiskers = 1.5 IQR)")
    fig.tight_layout()
    fig.savefig(OUT / "fig-latency.png", dpi=150)
    plt.close(fig)

# ---------------------------------------------------------------- capacity --
cap = load("capacity-*.csv")
if not cap.empty:
    labels = labels_present(cap)
    lines += ["## 2. Request capacity (ab -n 3000 -c 20, static page)", "",
              "| Condition | keep-alive | runs | requests/s mean | requests/s std dev "
              "| p95 ms (mean of runs) | failed |",
              "|---|---|---|---|---|---|---|"]
    for label in labels:
        for ka in ["no", "yes"]:
            x = cap[(cap["label"] == label) & (cap["keepalive"] == ka)]
            if x.empty:
                continue
            rps = x["requests_per_second"]
            lines.append(f"| {label} | {ka} | {len(x)} | {rps.mean():.0f} | {rps.std():.0f} | "
                         f"{x['p95_ms'].mean():.1f} | {int(x['failed'].sum())} |")
    lines.append("")

    fig, ax = plt.subplots(figsize=(7, 4))
    width = 0.38
    for i, (ka, name) in enumerate([("no", "new connection per request"), ("yes", "keep-alive")]):
        sel = [cap[(cap["label"] == l) & (cap["keepalive"] == ka)]["requests_per_second"]
               for l in labels]
        means = [x.mean() for x in sel]
        stds = [x.std() for x in sel]
        ax.bar(np.arange(len(labels)) + (i - 0.5) * width, means, width,
               yerr=stds, capsize=3, label=name)
    ax.set_xticks(np.arange(len(labels)), labels)
    ax.set_ylabel("requests per second")
    ax.set_title("Request capacity (error bars = std dev across runs)")
    ax.grid(axis="y", alpha=0.3)
    ax.legend()
    fig.tight_layout()
    fig.savefig(OUT / "fig-capacity.png", dpi=150)
    plt.close(fig)

# -------------------------------------------------------------- throughput --
thr = load("throughput-*.csv")
if not thr.empty:
    thr = thr[thr["http_code"] == 200]
    thr["mbit"] = thr["bytes_per_second"] * 8 / 1e6
    labels = labels_present(thr)
    lines += ["## 3. Bulk transfer throughput (20 MB download, Mbit/s)", "",
              "| Condition | n | mean | std dev | min | max |", "|---|---|---|---|---|---|"]
    for label in labels:
        x = thr[thr["label"] == label]["mbit"]
        lines.append(f"| {label} | {x.size} | {x.mean():.0f} | {x.std():.0f} | "
                     f"{x.min():.0f} | {x.max():.0f} |")
    lines.append("")

    fig, ax = plt.subplots(figsize=(6, 4))
    means = [thr[thr["label"] == l]["mbit"].mean() for l in labels]
    stds = [thr[thr["label"] == l]["mbit"].std() for l in labels]
    ax.bar(labels, means, yerr=stds, capsize=4)
    ax.set_ylabel("throughput (Mbit/s)")
    ax.set_title("20 MB download through the perimeter (error bars = std dev)")
    ax.grid(axis="y", alpha=0.3)
    fig.tight_layout()
    fig.savefig(OUT / "fig-throughput.png", dpi=150)
    plt.close(fig)

# --------------------------------------------------------------- resources --
res = load("resources-*.csv")
if not res.empty:
    labels = labels_present(res)
    lines += ["## 4. CPU use under load (percent of one core, mean of 5 samples)", "",
              "| Node | " + " | ".join(labels) + " |", "|---|" + "---|" * len(labels)]
    for node in ["edge", "core", "web", "app", "db"]:
        cells = [f"{res[(res['label'] == l) & (res['node'] == node)]['cpu_percent'].mean():.1f}"
                 for l in labels]
        lines.append(f"| {node} | " + " | ".join(cells) + " |")
    lines.append("")

# ----------------------------------------------------------- attack matrix --
def latest(profile: str) -> pd.DataFrame:
    files = sorted(EVIDENCE.glob(f"tests-{profile}-*.csv"))
    return pd.read_csv(files[-1]) if files else pd.DataFrame()


base_t, hard_t = latest("baseline"), latest("hardened")
if not base_t.empty and not hard_t.empty:
    a = base_t[base_t["type"] == "attack"][["id", "description", "outcome"]]
    a = a.rename(columns={"outcome": "baseline"})
    b = hard_t[hard_t["type"] == "attack"][["id", "outcome"]]
    b = b.rename(columns={"outcome": "hardened"})
    m = a.merge(b, on="id")
    lines += ["## 5. Attack outcomes, before and after", "",
              "| ID | Attack | Baseline | Hardened |", "|---|---|---|---|"]
    lines += [f"| {r.id} | {r.description} | {r.baseline} | {r.hardened} |" for r in m.itertuples()]
    nb = int((m["baseline"] == "EXPOSED").sum())
    nh = int((m["hardened"] == "EXPOSED").sum())
    lines += ["", f"**Attacks that succeeded: baseline {nb} of {len(m)}, "
                  f"hardened {nh} of {len(m)}.**", ""]

    fig, ax = plt.subplots(figsize=(9, 0.33 * len(m) + 1.2))
    grid = np.array([[1 if v == "EXPOSED" else 0 for v in m[c]]
                     for c in ["baseline", "hardened"]]).T
    ax.imshow(grid, cmap="RdYlGn_r", vmin=0, vmax=1, aspect="auto")
    ax.set_xticks([0, 1], ["baseline", "hardened"])
    ax.set_yticks(range(len(m)), [f"{r.id}  {r.description}" for r in m.itertuples()], fontsize=8)
    for y in range(len(m)):
        for x, c in enumerate(["baseline", "hardened"]):
            ax.text(x, y, m[c].iloc[y], ha="center", va="center", fontsize=7)
    ax.set_title("Attack outcome matrix")
    fig.tight_layout()
    fig.savefig(OUT / "fig-attacks.png", dpi=150)
    plt.close(fig)

    ctrl = hard_t[hard_t["type"] == "ctrl"]
    lines += ["## 6. Control verification (hardened profile)", "",
              "| ID | Control | Result |", "|---|---|---|"]
    lines += [f"| {r.id} | {r.description} | {r.outcome} |" for r in ctrl.itertuples()]
    lines.append("")

(OUT / "summary.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
print(f"\nWritten: {OUT}/summary.md and figures in {OUT}/")
